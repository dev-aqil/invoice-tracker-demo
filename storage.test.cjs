const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const { randomUUID } = require('node:crypto');
let stored = null;
const context = { crypto: { randomUUID }, localStorage: { getItem: () => stored, setItem: (_, value) => { stored = value; } } };
const source = fs.readFileSync('public/storage.js', 'utf8');
vm.runInNewContext(source, context);
assert.equal(context.invoiceStore.load().length, 0);
assert.throws(() => context.invoiceStore.add('', 5));
assert.throws(() => context.invoiceStore.add('Client', -1));
context.invoiceStore.add(' Client ', '12.50');
const id = context.invoiceStore.load()[0].id;
vm.runInNewContext(source, context);
assert.equal(context.invoiceStore.load()[0].amount, 12.5);
context.invoiceStore.toggle(id);
assert.equal(context.invoiceStore.load()[0].paid, true);
context.invoiceStore.remove(id);
assert.equal(context.invoiceStore.load().length, 0);
stored = 'broken';
assert.throws(() => context.invoiceStore.add('Client', 1));
assert.equal(stored, 'broken');
console.log('PASS: validation, persistence, toggle, delete and corrupt-data protection');
